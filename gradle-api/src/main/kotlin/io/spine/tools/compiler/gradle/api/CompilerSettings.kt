package io.spine.tools.compiler.gradle.api

import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.Property

/**
 * Configures the code generation process performed by the Compiler.
 */
public interface CompilerSettings {

    /**
     * Passes the given names of Java classes to the Compiler as classes
     * extending the `io.spine.tools.compiler.plugin.Plugin` class.
     */
    public fun plugins(vararg classNames: String)

    /**
     * The subdirectories to which the files generated from Protobuf are placed.
     *
     * If the code files that need processing are placed in a few subdirectories within
     * `$buildDir/generated/source/proto`, (e.g. `java` and `spine`), after processing,
     * the same directory structure is preserved in the [targetBaseDir].
     *
     * The default value is `"java"`.
     */
    public var subDirs: List<String>

    /**
     * The base directory where the files generated by the Compiler are placed.
     *
     * By default, points at the `$projectDir/generated/` directory.
     */
    @Deprecated(message = "Please use `outputBaseDir` instead.", ReplaceWith("outputBaseDir"))
    public var targetBaseDir: Any

    /**
     * The path to the root directory with the generated code.
     *
     * By default, points at the `$projectDir/generated/` directory.
     */
    public val outputBaseDir: DirectoryProperty

    /**
     * Tells whether the Protobuf version check is disabled in the Compiler process.
     *
     * The Protobuf runtime checks that the code generated by `protoc` is compatible
     * with the runtime — in particular, that it is not newer than the runtime — and
     * fails otherwise. Such a mismatch may occur when the plugins passed to the Compiler
     * are built with a version of Protobuf different from the one used by the Compiler.
     *
     * When set to `true`, the `TEMPORARILY_DISABLE_PROTOBUF_VERSION_CHECK` environment
     * variable is set to `true` for the Compiler process, which turns the check off.
     * This is a shortcut for setting the variable in the environment of
     * the `LaunchSpineCompiler` tasks directly.
     *
     * When set to `false`, the environment of the Compiler process is left as is,
     * so a variable set in the environment of the build still reaches the Compiler.
     *
     * The setting affects neither the Gradle daemon nor the `protoc` plugins.
     * If the check fails there, set the variable in the environment of the build instead.
     *
     * Use this setting only as a temporary workaround until the Protobuf versions
     * are aligned.
     *
     * The default value is `false`.
     *
     * Example (`build.gradle.kts`):
     *
     * ```kotlin
     * spine {
     *     compiler {
     *         disableProtobufVersionCheck.set(true)
     *     }
     * }
     * ```
     */
    public val disableProtobufVersionCheck: Property<Boolean>
}
